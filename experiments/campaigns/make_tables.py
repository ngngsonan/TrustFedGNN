def tab_c25_known_labels() -> str:
    c25 = load("campaigns/C25b_control_pokecz_known.json")
    raw = c25["per_seed_raw"]
    fu = {x["seed"]: x for x in raw["M1_fu_shapley"]}
    fa = {x["seed"]: x for x in raw["A0_fedavg"]}
    seeds = sorted(fu)
    delta = {m: [fu[s][m] - fa[s][m] for s in seeds] for m in ("auc", "dpd_hard", "eod")}
    ni = noninferiority(delta["auc"], delta=0.01, n=10000, seed=0)
    require(ni["pass"] is True, "AUC non-inferiority at the 0.01 margin")
    pv = {m: wilcoxon_p(delta[m]) for m in delta}
    require(pv["dpd_hard"] >= 0.05 and pv["eod"] >= 0.05, "no fairness difference is significant")
    rows = []
    for arm, lab in (("A0_fedavg", "FedAvg"), ("M1_fu_shapley", "FU-Alignment")):
        x = c25["arms"][arm]
        rows.append(f"{lab} & {x['auc']['mean']:.4f} $\\pm$ {x['auc']['std']:.4f} & {x['dpd_hard']['mean']:.4f} $\\pm$ "
                    f"{x['dpd_hard']['std']:.4f} & {x['eod']['mean']:.4f} $\\pm$ {x['eod']['std']:.4f} \\\\")
    md = {m: float(np.mean(v)) for m, v in delta.items()}
    tex = header({"campaigns/C25b_control_pokecz_known.json": c25}) + rf"""\begin{{table}}[t]
\centering
\footnotesize
\caption{{\textbf{{Pokec-z known-label control supports AUC non-inferiority, not fairness superiority.}} Mean $\pm$ sample SD over {len(seeds)} paired seeds. FU-Alignment minus FedAvg: AUC ${md['auc']:+.6f}$ (Wilcoxon $p={pv['auc']:.3f}$), DPD ${md['dpd_hard']:+.6f}$ ($p={pv['dpd_hard']:.3f}$), and EOD ${md['eod']:+.6f}$ ($p={pv['eod']:.3f}$). The prespecified AUC non-inferiority margin is 0.01; the one-sided 95\% bootstrap lower bound is ${ni['ci_lower']:.6f}$.}}
\label{{tab:c25_known_labels}}
\setlength{{\tabcolsep}}{{5pt}}
\begin{{tabular}}{{lrrr}}
\toprule
\textbf{{Rule}} & \textbf{{AUC}} & \textbf{{DPD}} & \textbf{{EOD}} \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    return write("tab_c25_known_labels", tex)


