    brows = []
    for arm, lab in blab:
        sc, st = sel(arm, "scaling"), sel(arm, "stealth")
        norms = col(sc, "g_agg_norm")
        n_inf = sum(1 for x in norms if not math.isfinite(x))
        norm_cell = "Diverged$^\\dagger$" if n_inf == len(norms) else f"${f(mean(norms), 2)} \\pm {f(sd(norms), 2)}$"
