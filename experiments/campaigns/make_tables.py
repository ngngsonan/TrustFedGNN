"""Generate every manuscript table from the JSON artifacts.

    python -m experiments.campaigns.make_tables            # writes build/tables/*.tex
    python -m experiments.campaigns.make_tables --only tab_two_tier

Rules this script enforces:
  * No result value is typed in this file. Every number is read from an artifact
    in results/ and recomputed from per-seed records (mean, sample SD with ddof=1).
  * Every caption carries one conclusion sentence. The direction of that sentence
    is checked with `require(...)` against the same numbers; if the data do not
    support it, generation stops instead of printing a false caption.
  * Output goes to build/tables/ (not tracked) so it can be diffed against
    manuscript_inforsci/tables/ before anything is replaced.
  * Each output starts with a provenance comment: artifact path(s) and commit(s).
"""
