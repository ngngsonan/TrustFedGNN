def _sota_panel(d: dict, control: dict | None) -> tuple:
    runs = d["raw_runs"]
    ours = runs["fedfairgnn"]
    pv = {m: paired(runs[m], ours, "auc", lower_is_better=False)["p_wilcoxon"] for m, _ in SOTA_ROWS if m != "fedfairgnn"}
    holm = holm_bonferroni(pv)
    best = {}
    for key, lower in [("auc", False), ("dpd_hard", True), ("eod", True)]:
        vals = {m: mean(col(runs[m], key)) for m, _ in SOTA_ROWS}
        best[key] = (min if lower else max)(vals, key=vals.get)
    auc_means = {m: mean(col(runs[m], "auc")) for m, _ in SOTA_ROWS}
    worst_auc = min(auc_means, key=auc_means.get)
    lines = []
    for m, lab in SOTA_ROWS:
        r = runs[m]
        dp = "\\checkmark" if r[0]["config"].get("dp_enabled") else "$\\times$"
        star = "$^\\star$" if holm.get(m) else ""
        cells = [pm(col(r, k), bold=(best[k] == m)) + (star if k == "auc" else "")
                 + ("$^{\\ddagger}$" if k != "auc" and best[k] == m and m == worst_auc else "") for k in ("auc", "dpd_hard", "eod")]
        om = mean(col(r, "omega_w"))
        lines.append(f"{lab} & {dp} & " + " & ".join(cells) + f" & {f(om)} \\\\")
        if m == "fedavg-gcn" and control is not None:
            a0 = control["per_seed_raw"]["A0_fedavg"] if "A0_fedavg" in control.get("per_seed_raw", {}) else None
            if a0:
                cc = " & ".join("\\textit{" + pm(col(a0, k)) + "}" for k in ("auc", "dpd_hard", "eod"))
                dp_on = source_value(PINNED, "experiments/colab/run_revision_gpu.py",
                                     r'"A0_fedavg": dict\([^)]*dp_enabled=(True|False)') == "True"
                lines.append(f"\\textit{{FedAvg, matched backbone}}$^{{\\P}}$ & {'\\checkmark' if dp_on else '$\\times$'} & {cc} & {f(0.0)} \\\\")
    return lines, pv, holm, best


