_MODEL_RE = r'(?:\bmodel=|"model":\s*)"([a-z0-9_]+)"'
_DP_RE = r'(?:\bdp_enabled=|"dp_enabled":\s*)(True|False)'


def runner_settings(commit: str, runner: str, canon) -> Dict[str, set]:
    """Literal settings in a runner's config construction at `commit`.

    Collects model / dp_enabled / local_epochs literals and method presets (method="...",
    resolved through experiments/methods.py at the same commit). A key the runner never sets
    literally takes the canonical default when the runner builds ExperimentConfig.canonical(...)."""
    import re
    import subprocess
    show = lambda path: subprocess.run(["git", "-C", ROOT, "show", f"{commit}:{path}"], capture_output=True, text=True).stdout
    src = show(runner)
    out = {"model": set(re.findall(_MODEL_RE, src)),
           "dp_enabled": {m == "True" for m in re.findall(_DP_RE, src)},
           "local_epochs": {int(m) for m in re.findall(r"\blocal_epochs=(\d+)", src)},
           "dirichlet_alpha": {float(m) for m in re.findall(r"\bdirichlet_alpha=([\d.]+)", src)},
           "num_clients": {int(m) for m in re.findall(r"\b(?:num_clients|NUM_CLIENTS)\s*=\s*(\d+)", src)},
           "rounds": set()}
    pr = re.search(r"PROBE_ROUNDS\s*=\s*\[([\d,\s]+)\]", src)
    if pr and re.search(r"rounds=max\(PROBE_ROUNDS\)\s*\+\s*(\d+)", src):
        out["rounds"] = {max(int(x) for x in pr.group(1).split(",")) + int(re.search(r"rounds=max\(PROBE_ROUNDS\)\s*\+\s*(\d+)", src).group(1))}
    methods_src = None
    for meth in set(re.findall(r'\bmethod="([a-z0-9_-]+)"', src)):
        methods_src = methods_src or show("experiments/methods.py")
        m = re.search(r'"' + re.escape(meth) + r'":\s*dict\(([^)]*)\)', methods_src)
        if m:
            out["model"].update(re.findall(r'model="([a-z0-9_]+)"', m.group(1)))
            out["dp_enabled"].update(x == "True" for x in re.findall(r"dp_enabled=(True|False)", m.group(1)))
    if "ExperimentConfig.canonical(" in src or "apply_method" in src or out["model"]:
        for key in ("model", "dp_enabled", "local_epochs", "num_clients"):
            if not out[key]:
                out[key] = {getattr(canon, key)}
        if not out["dirichlet_alpha"] and not re.search(r"\bpartition\s*=", src):
            out["dirichlet_alpha"] = {canon.dirichlet_alpha}
    return out


