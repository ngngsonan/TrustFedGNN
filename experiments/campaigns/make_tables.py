def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--check", action="store_true", help="fail if build/tables differs from manuscript/tables")
    a = ap.parse_args()
    failed = 0
    for name, fn in TABLES.items():
        if a.only and name not in a.only:
            continue
        try:
            path = fn()
            print(f"[ok] {name:42s} -> {os.path.relpath(path, ROOT)}")
            if a.check:
                ref = os.path.join(MANUSCRIPT_TABLES, f"{name}.tex")
                if not (os.path.exists(ref) and filecmp.cmp(path, ref, shallow=False)):
                    failed += 1
                    print(f"[DIFF] {name}: build/tables differs from manuscript/tables")
        except Exception as e:  # report every table, then fail
            failed += 1
            print(f"[FAIL] {name}: {type(e).__name__}: {e}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
