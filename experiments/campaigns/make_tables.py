def source_value(commit: str, runner: str, pattern: str) -> str:
    """First capture group of `pattern` in `runner` at `commit` (raises if absent)."""
    import re
    import subprocess
    src = subprocess.run(["git", "-C", ROOT, "show", f"{commit}:{runner}"], capture_output=True, text=True, check=True).stdout
    m = re.search(pattern, src)
    if not m:
        raise RuntimeError(f"{runner}@{commit[:8]}: pattern not found: {pattern}")
    return m.group(1)


def pinned_call_kwargs(runner: str, pattern: str) -> Dict[str, float]:
    """Read keyword constants a runner hard-codes at the pinned commit (when the
    artifact itself does not record them). Raises if the pattern is absent."""
    import re
    import subprocess
    src = subprocess.run(["git", "-C", ROOT, "show", f"{PINNED}:{runner}"], capture_output=True, text=True, check=True).stdout
    m = re.search(pattern, src)
    if not m:
        raise RuntimeError(f"{runner}@{PINNED[:8]}: pattern not found: {pattern}")
    return {k: float(v) for k, v in m.groupdict().items()}


def device_label(*docs: dict) -> str:
    devs = set()
    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k == "device" and isinstance(v, str):
                    devs.add(v)
                else:
                    walk(v)
        elif isinstance(o, list):
            for v in o[:2000]:
                walk(v)
    for d in docs:
        walk(d.get("manifest") or d.get("_manifest") or {})
    names = {"cuda": "CUDA GPU", "cpu": "CPU"}
    return " + ".join(sorted(names.get(x, x) for x in devs)) or "unknown"


CFG_KEYS = ("num_clients", "rounds", "local_epochs", "dirichlet_alpha", "partition_by", "partition", "dataset", "model", "dp_enabled")


def config_values(d: dict, skip: Sequence[str] = ()) -> Dict[str, set]:
    """Collect every value of the configuration keys found anywhere in an artifact."""
    d = {k: v for k, v in d.items() if k not in skip}
    out: Dict[str, set] = {k: set() for k in CFG_KEYS}
    out["seed"] = set()
    def walk(o, depth=0):
        if depth > 7:
            return
        if isinstance(o, dict):
            for k, v in o.items():
                if k in CFG_KEYS and isinstance(v, (int, float, str)) and (not isinstance(v, bool) or k == "dp_enabled"):
                    out[k].add(v)
                elif k == "seed" and isinstance(v, int):
                    out["seed"].add(v)
                elif k == "seeds" and isinstance(v, list) and all(isinstance(x, int) for x in v):
                    out["seed"].update(v)
                elif k == "datasets" and isinstance(v, list):
                    out["dataset"].update(x for x in v if isinstance(x, str))
                else:
                    walk(v, depth + 1)
        elif isinstance(o, list):
            for v in o:
                walk(v, depth + 1)
    walk(d)
    return out


