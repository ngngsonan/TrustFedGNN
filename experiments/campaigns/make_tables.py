def supp_labels() -> str:
    lines = [
        "% Auto-generated by make_tables.py - do not edit directly",
        "% Shared label macros for main manuscript and supplementary material",
    ]
    for i, (tab_name, camel, label) in enumerate(SUPP_TABLE_ORDER, 1):
        val = f"S{i}"
        lines.append(f"\\newcommand{{\\STab{camel}}}{{{val}}} % {label}")
        if camel == "Config":
            lines.append(f"\\newcommand{{\\STabExperimentConfig}}{{{val}}} % {label}")
    path = os.path.join(ROOT, "build", "supp_labels.tex")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    a = ap.parse_args()
    failed = 0
    for name, fn in TABLES.items():
        if a.only and name not in a.only:
            continue
        try:
            print(f"[ok] {name:28s} -> {os.path.relpath(fn(), ROOT)}")
        except Exception as e:  # report every table, then fail
            failed += 1
            print(f"[FAIL] {name}: {type(e).__name__}: {e}")
    if not a.only:
        print(f"[ok] figure captions -> {os.path.relpath(figure_captions(), ROOT)}")
        print(f"[ok] inline numbers -> {os.path.relpath(inline_numbers(), ROOT)}")
        print(f"[ok] supp labels    -> {os.path.relpath(supp_labels(), ROOT)}")
    return 1 if failed else 0


