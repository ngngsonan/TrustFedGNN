def pin_fill(cid: str, v: Dict[str, set], canon) -> None:
    import re
    import subprocess
    if cid not in PIN_FILL:
        return
    runner, rx = PIN_FILL[cid]
    src = subprocess.run(["git", "-C", ROOT, "show", f"{PINNED}:{runner}"], capture_output=True, text=True, check=True).stdout
    for key in ("num_clients", "rounds", "local_epochs", "dirichlet_alpha"):
        if v[key]:
            continue
        if key in rx:
            m = re.search(rx[key], src)
            if not m:
                raise RuntimeError(f"{cid}: {key} not found in {runner}@{PINNED[:8]}")
            v[key] = {float(m.group(1)) if "." in m.group(1) else int(m.group(1))}
        elif "ExperimentConfig.canonical(" in src and not re.search(rf"\b{key}\s*=", src):
            v[key] = {getattr(canon, key)}
    if not v["partition_by"] and "ExperimentConfig.canonical(" in src and not re.search(r"\bpartition_by\s*=", src):
        v["partition_by"] = {canon.partition_by}


