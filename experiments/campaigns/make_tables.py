def holdout_stats(name: str) -> dict:
    """Server-holdout size and mean degree, computed exactly as the trainer does
    (canonical seed and size), on the locally cached dataset. No training."""
    from src.config import ExperimentConfig
    from src.data import load_dataset, carve_server_holdout
    import warnings
    cfg = ExperimentConfig.canonical()
    data = load_dataset(name, root=os.path.join(ROOT, cfg.data_root) if not os.path.isabs(cfg.data_root) else cfg.data_root, seed=cfg.seed)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        hold, _ = carve_server_holdout(data, cfg.fu_holdout_size, seed=cfg.seed)
    deg = lambda g: float(g.edge_index.shape[1]) / float(g.num_nodes)
    return {"size": int(hold.num_nodes), "share": hold.num_nodes / data.num_nodes,
            "deg_full": deg(data), "deg_holdout": deg(hold), "requested": int(cfg.fu_holdout_size), "seed": int(cfg.seed)}


