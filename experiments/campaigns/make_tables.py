"""Generate every table included by the manuscript and its Supplementary Information.

    python -m experiments.campaigns.make_tables            # writes build/tables/**.tex
    python -m experiments.campaigns.make_tables --check    # also diffs against manuscript/tables

Rules this script enforces:
  * No result value is typed in this file. Every number is read from an artifact in
    results/ (or from results/campaigns/analysis/discover_ai.json, which
    analyze_discover_ai.py recomputes from per-seed records).
  * Every caption claim is checked with `require(...)` against the same numbers; if the
    data do not support it, generation stops instead of printing a false caption.
  * Each output starts with a provenance comment: artifact path(s) and commit(s).
"""
from __future__ import annotations

