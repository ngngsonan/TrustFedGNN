    c_a = float(source_value(PINNED, "experiments/run_canonical_suite.py", r"attack_intensity=([\d.]+)"))
    rm_commit = rm["manifest"]["git_commit"]
    c_b = float(source_value(rm_commit, "experiments/revision/rescale_median_ablation.py", r'attack_intensity=([\d.]+) if attack == "scaling"'))
