# --------------------------------------------------------------------------- helpers
class CaptionNotSupported(AssertionError):
    pass


def require(cond: bool, what: str) -> None:
    if not cond:
        raise CaptionNotSupported(f"caption claim not supported by the data: {what}")


def load(rel: str) -> dict:
    with open(os.path.join(RES, rel)) as f:
        return json.load(f)


def commit_of(d: dict) -> str:
    m = d.get("manifest") or d.get("_manifest") or {}
    return str(m.get("git_commit") or "unknown")[:8]


def finite(xs: Sequence) -> List[float]:
    return [float(x) for x in xs if x is not None and math.isfinite(float(x))]


def mean(xs: Sequence) -> float:
    v = finite(xs)
    return float(np.mean(v)) if v else float("nan")


def sd(xs: Sequence) -> float:
    v = finite(xs)
    return float(np.std(v, ddof=1)) if len(v) > 1 else 0.0


def f(x: float, d: int = 4) -> str:
    return "---" if x is None or not math.isfinite(x) else f"{x:.{d}f}"


def pm(xs: Sequence, d: int = 4, bold: bool = False) -> str:
    s = f"{f(mean(xs), d)} $\\pm$ {f(sd(xs), d)}"
    return f"\\textbf{{{s}}}" if bold else s


def ptex(p: float) -> str:
    if p < 1e-5:
        return "p<10^{-5}"
    if p < 1e-3:
        return f"p={p:.1e}".replace("e-0", "\\times 10^{-").replace("e-", "\\times 10^{-") + "}"
    return f"p={p:.3f}"


def header(sources: Dict[str, dict]) -> str:
    lines = [f"%% generated by experiments/campaigns/make_tables.py -- do not edit by hand"]
    for path, d in sources.items():
        lines.append(f"%% source: results/{path} (commit {commit_of(d)})")
    return "\n".join(lines) + "\n"


def write(name: str, tex: str) -> str:
    path = os.path.join(OUT, f"{name}.tex")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(tex)
    return path


def col(records: List[dict], key: str) -> List[float]:
    return [r.get(key) for r in records]


def by_seed(records: List[dict], key: str) -> Dict[int, float]:
    return {int(r["seed"]): r.get(key) for r in records}


def paired(a: List[dict], b: List[dict], key: str, lower_is_better: bool = True) -> dict:
    """Seed-paired comparison on the seeds where both values are finite."""
    sa, sb = by_seed(a, key), by_seed(b, key)
    seeds = sorted(s for s in sa if s in sb and sa[s] is not None and sb[s] is not None
                   and math.isfinite(sa[s]) and math.isfinite(sb[s]))
    rep = paired_report([sa[s] for s in seeds], [sb[s] for s in seeds], lower_is_better=lower_is_better)
    rep["n"] = len(seeds)
    return rep


